import 'dart:async';

import 'package:enough_mail/enough_mail.dart';

/// Thin IMAP polling helper used by the E2E suite to fetch the real
/// confirmation link sent by the backend after signup.
///
/// This intentionally uses the *real* mailbox provided for testing rather
/// than a backend test-only endpoint, so the suite exercises the actual
/// mail-sending path end-to-end.
class MailClientHelper {
  MailClientHelper({
    required this.email,
    required this.password,
    required this.imapHost,
    this.imapPort = 993,
  });

  final String email;
  final String password;
  final String imapHost;
  final int imapPort;

  static final RegExp _confirmLinkPattern = RegExp(
    r'https?://[^\s"<>]*/accounts/confirm-email\?token=[^\s"<>]*',
  );

  /// Deletes any pre-existing "Confirm your Music Room account" emails from
  /// the inbox so a stale message from a previous/failed run can't be
  /// mistaken for the one generated by this run.
  Future<void> purgeExistingConfirmationEmails() async {
    final client = await _connect();
    try {
      await _deleteMatching(
        client,
        subjectContains: 'Confirm your Music Room account',
      );
    } finally {
      await client.disconnect();
    }
  }

  /// Polls the inbox until an email with the confirmation subject arrives,
  /// then extracts and returns the `/accounts/confirm-email?token=...` link.
  /// The message is deleted afterwards to keep the shared inbox clean.
  Future<String> waitForConfirmationLink({
    Duration timeout = const Duration(seconds: 45),
    Duration pollInterval = const Duration(seconds: 3),
  }) async {
    final client = await _connect();
    try {
      final deadline = DateTime.now().add(timeout);
      while (DateTime.now().isBefore(deadline)) {
        final mailbox = await client.selectInbox();
        if (mailbox.messagesExists == 0) {
          await Future.delayed(pollInterval);
          continue;
        }
        final messages = await client.fetchMessages(count: 10, page: 1);
        for (final message in messages) {
          final subject = message.decodeSubject() ?? '';
          if (!subject.contains('Confirm your Music Room account')) {
            continue;
          }
          final body =
              '${message.decodeTextPlainPart() ?? ''}\n${message.decodeTextHtmlPart() ?? ''}';
          final match = _confirmLinkPattern.firstMatch(body);
          if (match != null) {
            final link = match.group(0)!;
            await _deleteBySequenceId(client, message);
            return link;
          }
        }
        await Future.delayed(pollInterval);
      }
      throw TimeoutException(
        'Confirmation email was not received in $email within $timeout',
      );
    } finally {
      await client.disconnect();
    }
  }

  Future<void> _deleteMatching(
    MailClient client, {
    required String subjectContains,
  }) async {
    final mailbox = await client.selectInbox();
    if (mailbox.messagesExists == 0) {
      return;
    }
    final messages = await client.fetchMessages(count: 20, page: 1);
    // Delete highest sequence IDs first so earlier deletions don't shift the
    // sequence numbers of messages still pending deletion.
    final matching =
        messages
            .where(
              (message) =>
                  (message.decodeSubject() ?? '').contains(subjectContains),
            )
            .toList()
          ..sort((a, b) => (b.sequenceId ?? 0).compareTo(a.sequenceId ?? 0));
    for (final message in matching) {
      await _deleteBySequenceId(client, message);
    }
  }

  /// Deletes [message] using its plain (non-UID) sequence ID. This avoids a
  /// mismatch in `enough_mail` where `deleteMessage(expunge: true)` issues a
  /// plain `STORE` command even for UID-based sequences, causing an
  /// "Invalid messageset" error from the IMAP server.
  Future<void> _deleteBySequenceId(
    MailClient client,
    MimeMessage message,
  ) async {
    final sequenceId = message.sequenceId;
    if (sequenceId == null) {
      return;
    }
    await client.deleteMessages(
      MessageSequence.fromId(sequenceId),
      expunge: true,
    );
  }

  Future<MailClient> _connect() async {
    final account = MailAccount.fromManualSettings(
      name: email,
      email: email,
      incomingHost: imapHost,
      incomingPort: imapPort,
      incomingType: ServerType.imap,
      outgoingHost: imapHost,
      outgoingPort: 465,
      outgoingType: ServerType.smtp,
      password: password,
    );
    final client = MailClient(account, isLogEnabled: false);
    await client.connect();
    return client;
  }
}
